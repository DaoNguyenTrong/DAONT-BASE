// Derives the guide's colour tokens from the app's Tailwind theme, so the two can never drift and
// a fork that recolours the app recolours its guide for free.

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

type Block = Record<string, string>

function readBlock(css: string, opener: string): Block {
  const start = css.indexOf(opener)
  if (start === -1) return {}
  let depth = 0
  let end = start + opener.length - 1
  for (let i = end; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) {
      end = i
      break
    }
  }
  const block: Block = {}
  for (const match of css.slice(start, end).matchAll(/--color-([\w-]+)\s*:\s*([^;]+);/g)) {
    block[match[1]] = match[2].trim()
  }
  return block
}

export function parseThemeBlocks(css: string): { theme: Block; dark: Block } {
  return { theme: readBlock(css, '@theme {'), dark: readBlock(css, '.dark {') }
}

// Follows `var(--color-x)` chains: the declaring block first, then @theme.
function resolve(name: string, block: Block, theme: Block): string | undefined {
  let value = block[name] ?? theme[name]
  for (let hops = 0; value?.startsWith('var(') && hops < 10; hops++) {
    const ref = /^var\(\s*--color-([\w-]+)\s*\)$/.exec(value)?.[1]
    value = ref ? (block[ref] ?? theme[ref]) : undefined
  }
  return value
}

export function generateBrandTokensCss(css: string): string {
  const { theme, dark } = parseThemeBlocks(css)
  const wanted: [string, string, Block][] = [
    ...STEPS.map((n): [string, string, Block] => [`violet-${n}`, `accent-${n}`, theme]),
    ...STEPS.map((n): [string, string, Block] => [`leaf-${n}`, `leaf-${n}`, theme]),
    ['primary-200-dark', 'primary-200', dark],
    ['surface-900', 'surface-900', dark],
    ['surface-950', 'surface-950', dark],
  ]
  const missing: string[] = []
  const lines: string[] = []
  for (const [brand, source, block] of wanted) {
    const value = block[source] === undefined ? undefined : resolve(source, block, theme)
    if (!value || value.startsWith('var(')) missing.push(`--color-${source}`)
    else lines.push(`  --brand-${brand}: ${value};`)
  }
  if (missing.length > 0) throw new Error(`Missing tokens in tailwind.css: ${missing.join(', ')}`)
  return `/* Generated by scripts/sync-brand.ts from frontend/src/assets/styles/tailwind.css — do not edit. */\n:root {\n${lines.join('\n')}\n}\n`
}

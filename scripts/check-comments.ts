// Enforces .claude/rules/comments.md: at most MAX_LINES lines of MAX_WIDTH chars per comment.
// Usage: bun scripts/check-comments.ts [--staged | <path>...]  (default: the whole tracked tree)

import { spawnSync } from 'node:child_process'
import { readFileSync } from 'node:fs'

export const MAX_LINES = 3
// Without a width cap, three lines just grow long enough to hold a paragraph.
export const MAX_WIDTH = 120

const SOURCE = /\.(ts|tsx|mts|cts|js|mjs|cjs|vue|cs|css|scss)$/
const GENERATED = [
  /\/Migrations\/[^/]+\.Designer\.cs$/,
  /\/Migrations\/[^/]+ModelSnapshot\.cs$/,
  /^frontend\/src\/(api\/generated|typings)\//,
]
const DIRECTIVE =
  /eslint-(disable|enable)|@ts-(expect-error|ignore|nocheck)|prettier-ignore|@vitest-environment|istanbul ignore|c8 ignore|@vite-ignore|ReSharper (disable|restore)|<auto-generated|^\/\/\/ <reference /
const HISTORY =
  /\b(originally|previously|used to be|was (promoted|retuned|renamed|moved|replaced|changed)|no longer|per (the )?user|as discussed)\b/i

// One line per documented parameter or response: capping these would cap the API docs that
// flow into openapi.json, so only summary/remarks prose counts.
const PER_ITEM_TAG = /^<(param|typeparam|response)\b/
// A whole XML-doc element on one line: OpenAPI exports its line breaks verbatim, so it can't be
// wrapped without changing the contract. Still counts toward MAX_LINES.
const ONE_LINE_ELEMENT = /^\/\/\/\s*<(\w+)[^>]*>.*<\/\1>$/

export type Finding = { line: number; length: number; history?: string }

// Text left on a comment line once its markers are gone; '' for a delimiter- or tag-only line.
function commentText(line: string): string {
  const xmlDoc = line.startsWith('///')
  let text = line
    .replace(/^(\/\/\/?|\/\*\*?|\*\/|\*|<!--)/, '')
    .replace(/(\*\/|-->)$/, '')
    .trim()
  if (xmlDoc && PER_ITEM_TAG.test(text)) return ''
  if (xmlDoc) text = text.replace(/<[^>]+>/g, '').trim()
  return text
}

export function findComments(source: string): {
  long: Finding[]
  wide: Finding[]
  history: Finding[]
} {
  const long: Finding[] = []
  const wide: Finding[] = []
  const history: Finding[] = []
  let close: string | null = null
  let start = 0
  let length = 0

  const endBlock = () => {
    if (length > MAX_LINES) long.push({ line: start, length })
    start = 0
    length = 0
  }

  source.split('\n').forEach((raw, index) => {
    const line = raw.trim()
    let isComment = true
    if (close) {
      if (line.includes(close)) close = null
    } else if (line.startsWith('//')) {
      // single-line comment, nothing to track
    } else if (line.startsWith('/*')) {
      if (!line.slice(2).includes('*/')) close = '*/'
    } else if (line.startsWith('<!--')) {
      if (!line.slice(4).includes('-->')) close = '-->'
    } else {
      isComment = false
    }

    if (!isComment) return endBlock()
    if (DIRECTIVE.test(line)) return
    const text = commentText(line)
    if (!text) return
    const hint = HISTORY.exec(text)
    if (hint) history.push({ line: index + 1, length: 1, history: hint[0] })
    const width = raw.trimEnd().length
    if (width > MAX_WIDTH && !ONE_LINE_ELEMENT.test(line))
      wide.push({ line: index + 1, length: width })
    if (!start) start = index + 1
    length++
  })
  endBlock()
  return { long, wide, history }
}

export function isChecked(path: string): boolean {
  return SOURCE.test(path) && !GENERATED.some((pattern) => pattern.test(path))
}

function git(...args: string[]): string {
  const result = spawnSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${result.stderr}`)
  return result.stdout
}

function main(args: string[]): number {
  const staged = args.includes('--staged')
  const paths = staged
    ? git('diff', '--cached', '--name-only', '--diff-filter=ACMR')
    : args.length
      ? args.join('\n')
      : git('ls-files', 'backend', 'frontend', 'shared', 'scripts')
  let failed = 0
  for (const path of paths.split('\n').filter(isChecked)) {
    const source = staged ? git('show', `:${path}`) : readFileSync(path, 'utf8')
    const { long, wide, history } = findComments(source)
    for (const f of long) {
      console.error(`${path}:${f.line}: comment block has ${f.length} lines (max ${MAX_LINES})`)
      failed++
    }
    for (const f of wide) {
      console.error(`${path}:${f.line}: comment line is ${f.length} chars (max ${MAX_WIDTH})`)
      failed++
    }
    for (const f of history) {
      console.warn(`warning: ${path}:${f.line}: reads like change history ("${f.history}")`)
    }
  }
  if (failed) {
    console.error(`\n${failed} comment problem(s) — see .claude/rules/comments.md.`)
  }
  return failed ? 1 : 0
}

if (import.meta.main) process.exit(main(process.argv.slice(2)))
